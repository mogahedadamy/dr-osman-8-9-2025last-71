// الحصول على المدخلات حسب الحرف
export const getEntriesByLetter = (letter: string): EncyclopediaEntry[] => {
  return encyclopediaData.filter(entry => entry.letter === letter);
};

// البحث في الموسوعة
export const searchEncyclopedia = (query: string): EncyclopediaEntry[] => {
  const searchTerm = query.toLowerCase();
  return encyclopediaData.filter(entry => 
    entry.title.toLowerCase().includes(searchTerm) ||
    entry.definition.toLowerCase().includes(searchTerm) ||
    entry.tags.some(tag => tag.toLowerCase().includes(searchTerm))
  );
};

// الحصول على المدخلات حسب مستوى الإلحاح
export const getEntriesByUrgency = (urgencyLevel: 'low' | 'medium' | 'high'): EncyclopediaEntry[] => {
  return encyclopediaData.filter(entry => entry.urgencyLevel === urgencyLevel);
};

// الحصول على المدخلات حسب الفئة
export const getEntriesByCategory = (category: string): EncyclopediaEntry[] => {
  return encyclopediaData.filter(entry => entry.category === category);
};